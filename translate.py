"""
NordicAzur - automatic translation tool
=======================================
Reads the ENGLISH master text from index.html and updates translations.js.

Only texts that are NEW or CHANGED in English are translated, so any manual
corrections you made to existing translations are kept.

Usage (or simply double-click translate.bat on Windows):
    python translate.py            -> translate new/changed texts
    python translate.py --all      -> re-translate everything from scratch
    python translate.py --check    -> only list what would be translated

Translation engine:
  * DeepL (best quality) if you put your DeepL API key in a file called
    deepl_key.txt next to this script (free key: www.deepl.com/pro-api).
  * Otherwise Google Translate (free, no key needed).

Only the Python standard library is used - no extra installs required.
"""
import html.parser
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
HTML_FILE = os.path.join(HERE, "index.html")
JS_FILE = os.path.join(HERE, "translations.js")
KEY_FILE = os.path.join(HERE, "deepl_key.txt")

LANGUAGES = ["da", "sv", "no", "fr", "de", "nl", "it", "ru"]
DEEPL_CODES = {"da": "DA", "sv": "SV", "no": "NB", "fr": "FR", "de": "DE",
               "nl": "NL", "it": "IT", "ru": "RU"}
# Words that must never be translated
PROTECTED = ["NordicAzur", "Côte d'Azur", "Météo-France", "WhatsApp"]

VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link",
        "meta", "source", "track", "wbr"}


def norm(s):
    return re.sub(r"\s+", " ", s or "").strip()


class Extractor(html.parser.HTMLParser):
    """Collects the English text of every data-i18n element."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.texts = {}
        self.stack = []  # [key, depth, buffer]
        self.conflicts = []

    def _add(self, key, text):
        text = norm(text)
        if not key or not text:
            return
        if key in self.texts and self.texts[key] != text:
            self.conflicts.append(key)
        self.texts[key] = text

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if a.get("data-i18n-placeholder"):
            self._add(a["data-i18n-placeholder"], a.get("placeholder", ""))
        if a.get("data-i18n-alt"):
            self._add(a["data-i18n-alt"], a.get("alt", ""))
        if tag in VOID:
            return
        for item in self.stack:
            item[1] += 1
        if a.get("data-i18n"):
            self.stack.append([a["data-i18n"], 1, []])

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        for item in self.stack:
            item[1] -= 1
        while self.stack and self.stack[-1][1] <= 0:
            key, _, buf = self.stack.pop()
            self._add(key, "".join(buf))

    def handle_data(self, data):
        for item in self.stack:
            item[2].append(data)


def read_english():
    with open(HTML_FILE, encoding="utf-8") as f:
        p = Extractor()
        p.feed(f.read())
    if p.conflicts:
        print("WARNING: these labels are used for different texts, give them unique names:",
              ", ".join(sorted(set(p.conflicts))))
    return p.texts


def read_translations():
    if not os.path.exists(JS_FILE):
        return {"source": {}, "languages": {}}
    with open(JS_FILE, encoding="utf-8") as f:
        raw = f.read()
    start, end = raw.index("{"), raw.rindex("}")
    data = json.loads(raw[start:end + 1])
    data.setdefault("source", {})
    data.setdefault("languages", {})
    return data


def write_translations(data):
    body = json.dumps(data, ensure_ascii=False, indent=2)
    with open(JS_FILE, "w", encoding="utf-8") as f:
        f.write("// NordicAzur translations - generated by translate.py from the English text in index.html.\n")
        f.write("// You may correct a translation here by hand; it is kept until the English text changes.\n")
        f.write("window.NA_TRANSLATIONS = " + body + ";\n")


def protect(text):
    mapping = {}
    for i, word in enumerate(PROTECTED):
        if word in text:
            token = "[[%d]]" % i
            text = text.replace(word, token)
            mapping[token] = word
    return text, mapping


def unprotect(text, mapping):
    for token, word in mapping.items():
        text = re.sub(re.escape(token).replace(r"\ ", r"\s*"), word, text)
    return text


def translate_google(text, lang):
    url = ("https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&dt=t&tl="
           + lang + "&q=" + urllib.parse.quote(text))
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req, timeout=20) as r:
        data = json.loads(r.read().decode("utf-8"))
    return "".join(seg[0] for seg in data[0] if seg and seg[0])


def translate_deepl(text, lang, key):
    host = "api-free.deepl.com" if key.endswith(":fx") else "api.deepl.com"
    body = urllib.parse.urlencode({"text": text, "source_lang": "EN",
                                   "target_lang": DEEPL_CODES[lang]}).encode()
    req = urllib.request.Request("https://%s/v2/translate" % host, data=body,
                                 headers={"Authorization": "DeepL-Auth-Key " + key})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.loads(r.read().decode("utf-8"))["translations"][0]["text"]


def translate(text, lang, deepl_key):
    safe, mapping = protect(text)
    for attempt in range(3):
        try:
            if deepl_key:
                out = translate_deepl(safe, lang, deepl_key)
            else:
                out = translate_google(safe, lang)
            return unprotect(out, mapping)
        except Exception as e:  # network hiccup: wait and retry
            if attempt == 2:
                raise
            time.sleep(2 + attempt * 3)


def main():
    force = "--all" in sys.argv
    check_only = "--check" in sys.argv

    english = read_english()
    data = read_translations()
    source = data["source"]

    changed = [k for k, v in english.items() if force or norm(source.get(k)) != v]
    missing = {lang: [k for k in english if k not in data["languages"].get(lang, {})]
               for lang in LANGUAGES}
    removed = [k for k in source if k not in english]

    todo = {lang: sorted(set(changed) | set(missing[lang])) for lang in LANGUAGES}
    total = sum(len(v) for v in todo.values())

    print("English texts found in index.html:", len(english))
    print("New or changed English texts:     ", len(changed))
    for k in changed:
        print("   -", k, ":", english[k][:70])
    if removed:
        print("Texts removed from the page:      ", ", ".join(removed))

    if check_only:
        return
    if total == 0 and not removed:
        print("\nEverything is already up to date. Nothing to translate.")
        return

    deepl_key = ""
    if os.path.exists(KEY_FILE):
        with open(KEY_FILE, encoding="utf-8") as f:
            deepl_key = f.read().strip()
    deepl_key = os.environ.get("DEEPL_API_KEY", deepl_key)
    print("\nTranslation engine:", "DeepL" if deepl_key else "Google Translate (free)")

    errors = 0
    for lang in LANGUAGES:
        dict_ = data["languages"].setdefault(lang, {})
        for key in todo[lang]:
            try:
                dict_[key] = translate(english[key], lang, deepl_key)
                print("  [%s] %s" % (lang, key))
            except Exception as e:
                errors += 1
                print("  [%s] %s  FAILED: %s" % (lang, key, e))
                dict_.pop(key, None)
        for key in removed:
            dict_.pop(key, None)

    # Remember which English text each translation was made from
    data["source"] = {k: v for k, v in english.items()}
    if errors:
        # Mark failed keys as outdated so they are retried next time
        for lang in LANGUAGES:
            for key in todo[lang]:
                if key not in data["languages"][lang]:
                    data["source"][key] = ""
    write_translations(data)

    print("\nDone. translations.js has been updated." if not errors else
          "\nFinished with %d errors - run the tool again to retry them." % errors)


if __name__ == "__main__":
    try:
        main()
    finally:
        if os.name == "nt" and "--no-pause" not in sys.argv:
            input("\nPress Enter to close...")
